// Only slugs that also have a written content component registered in
// src/content/guides/index.ts get a live route; the rest exist here so the
// interlink graph and hub page structure are already correct as content
// is added incrementally (publishing a metadata-only page would be thin
// content and hurts SEO, so unwritten guides are simply not linked yet).

